def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in ("ar", "en") else "ar"


def current() -> str:
    return _lang


def t(key: str, **values) -> str:
    pair = TEXT.get(key)
    if pair is None:
        return key
    text = pair[0] if _lang == "ar" else pair[1]
    if values:
        try:
            return text.format(**values)
        except (KeyError, IndexError, ValueError):
            return text
    return text
